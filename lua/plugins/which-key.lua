return {
  "folke/which-key.nvim",
  opts = function(_, opts)
    opts.replace = opts.replace or {}
    opts.replace.desc = {
      { "<Plug>%(?(.*)%)?", "%1" },
      { "^%+", "" },
      { "<[cC]md>", "" },
      { "<[cC][rR]>", "" },
      { "<[sS]ilent>", "" },
      { "^lua%s+", "" },
      { "^call%s+", "" },
      { "^:%s*", "" },
      function(desc)
        local translation = translations[desc]
        if translation then
          return ("%s (%s)"):format(desc, translation)
        end

        local count = desc:match("^(%d+) keymaps?$")
        if count then
          return ("%s (%s 个快捷键)"):format(desc, count)
        end

        local action, option = desc:match("^(%a+) (.+)$")
        if action ~= "Enable" and action ~= "Disable" then
          action, option = nil, nil
        end
        local option_translation = option and translations["Toggle " .. option]
        if option_translation then
          option_translation = option_translation:gsub("^切换", "")
          local action_translation = action == "Enable" and "启用" or "禁用"
          return ("%s (%s%s)"):format(desc, action_translation, option_translation)
        end

        return desc
      end,
    }
  end,
}
